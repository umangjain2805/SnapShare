import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import { mkdir } from 'node:fs/promises';
import { createApp } from '../../apps/api/src/app.js';
import { parseEnv } from '../../apps/api/src/config/env.js';
import { connectDatabase, disconnectDatabase } from '../../apps/api/src/infrastructure/database.js';
import { User, Session } from '../../apps/api/src/modules/auth/model.js';

const mongo = await MongoMemoryReplSet.create({ replSet: { count: 1, storageEngine: 'wiredTiger' } });
await connectDatabase(mongo.getUri());
await Promise.all([User.init(), Session.init()]);
const env = parseEnv({ NODE_ENV: 'test', APP_URL: 'http://localhost:5173', MONGODB_URI: mongo.getUri(), LOG_LEVEL: 'silent' });
const api = createApp(env).listen(0, '127.0.0.1');
await new Promise<void>(resolve => api.once('listening', resolve));
const address = api.address();
if (!address || typeof address === 'string') throw new Error('API did not bind');
const vite = await createServer({ root: 'apps/web', server: { host: '127.0.0.1', port: 5173, strictPort: true, proxy: { '/api': `http://127.0.0.1:${address.port}` } } });
let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
try {
  await vite.listen();
  browser = await chromium.launch({ channel: process.env.CHROMIUM_CHANNEL || undefined });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await mkdir('test-results', { recursive: true });
  await page.goto('http://localhost:5173/dashboard');
  await expect(page).toHaveURL(/\/signin$/);
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/signin-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Create an account' }).click();
  await page.getByLabel('Full name').fill('Alex Morgan');
  await page.getByLabel('Email address').fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('browser-test-passphrase');
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page.getByRole('heading', { name: 'Hello, Alex.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Hello, Alex.' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page).toHaveURL(/\/signin$/);
  await page.getByLabel('Email address').fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('Invalid email or password');
  await page.getByLabel('Password', { exact: true }).fill('browser-test-passphrase');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Hello, Alex.' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page).toHaveURL(/\/signin$/);
  await page.screenshot({ path: 'test-results/signin-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  process.stdout.write('Browser smoke passed: route protection, registration, reload, logout, invalid login, login, mobile layout.\n');
} finally {
  await browser?.close(); await vite.close();
  await new Promise<void>(resolve => api.close(() => resolve()));
  await disconnectDatabase(); await mongo.stop();
}
